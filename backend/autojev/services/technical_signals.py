"""Deterministic browser-signal triage and durable per-scenario evidence.

An observed request error is not a confirmed business defect.  This module is
deliberately local: it never asks a model to confirm a browser event, and never
allows documentation generated by a model to replace execution evidence.
"""

from __future__ import annotations

import copy
import hashlib
import json
import re
from dataclasses import asdict
from datetime import datetime
from typing import Any
from urllib.parse import urljoin, urlsplit

from autojev.domain.models import ActionResult, AgentDecision, Observation
from autojev.services.report_localization import action_label, check_label, report_text

_RESOURCE_HTTP = re.compile(
    r"Failed to load resource.*?status of (\d{3})", re.IGNORECASE
)
_RESOURCE_NETWORK = re.compile(
    r"Failed to load resource.*?(net::[A-Z_]+)", re.IGNORECASE
)
_TELEMETRY_HOSTS = (
    "backtrace.io",
    "sentry.io",
    "bugsnag.com",
    "google-analytics.com",
    "analytics.google.com",
    "segment.io",
    "segment.com",
    "doubleclick.net",
)


def timestamp(value: Any) -> float | None:
    try:
        return datetime.fromisoformat(str(value).replace("Z", "+00:00")).timestamp()
    except (TypeError, ValueError):
        return None


def _origin(value: Any) -> tuple[str, str, int | None] | None:
    try:
        parsed = urlsplit(str(value or ""))
        if not parsed.hostname or parsed.scheme not in {"http", "https"}:
            return None
        port = parsed.port or (443 if parsed.scheme == "https" else 80)
        host = parsed.hostname.casefold()
        # example.com and www.example.com are the same application: a start URL
        # without "www." is routinely redirected to it, and the run and the
        # report must classify the same request identically.
        if host.startswith("www.") and host.count(".") >= 2:
            host = host[4:]
        return parsed.scheme.casefold(), host, port
    except (TypeError, ValueError):
        return None


def signal_signature(issue: dict[str, Any]) -> str:
    stable = {
        key: issue.get(key)
        for key in ("type", "method", "message", "url", "status_code")
    }
    return hashlib.sha256(json.dumps(stable, sort_keys=True).encode()).hexdigest()


def signal_occurrence_id(issue: dict[str, Any], fallback_time: str = "") -> str:
    """Repeated requests get distinct IDs; rereading a buffer does not."""

    identity = {
        "signature": signal_signature(issue),
        "occurred_at": issue.get("occurred_at") or fallback_time,
        "request_id": issue.get("request_id"),
    }
    return (
        "signal-"
        + hashlib.sha256(json.dumps(identity, sort_keys=True).encode()).hexdigest()[:24]
    )


def classify_signal(issue: dict[str, Any], app_url: str) -> dict[str, Any]:
    """Classify an observation without asserting an unproven causal defect.

    ``affects_verdict`` describes the technical-health guard, not a confirmed
    business bug. A same-origin HTTP/runtime failure remains negative technical
    evidence. External failures and resource-console lines without an identified
    request remain visible but cannot independently fail a functional scenario.
    """

    classified = copy.deepcopy(issue)
    kind = str(
        issue.get("type")
        or issue.get("kind")
        or ("http" if issue.get("status_code") else "")
    )
    message = str(issue.get("message") or "")
    source_url = str(issue.get("url") or "")
    source_origin = _origin(
        urljoin(app_url, source_url) if source_url.startswith("/") else source_url
    )
    app_origin = _origin(app_url)
    same_origin = source_origin is not None and source_origin == app_origin
    host = source_origin[1] if source_origin else ""
    telemetry = any(
        host == domain or host.endswith("." + domain) for domain in _TELEMETRY_HOSTS
    )
    cancellation = bool(
        re.search(
            r"net::ERR_ABORTED|NS_BINDING_ABORTED|request (?:was )?cancel(?:led|ed)",
            message,
            re.IGNORECASE,
        )
    )
    affects = False
    impact = "informational"
    if cancellation:
        classification, label = "request_cancelled", "Requisição cancelada"
        reason = "O navegador cancelou a requisição; o cancelamento isolado não comprova falha funcional."
    elif telemetry and not same_origin and kind in {"http", "network"}:
        classification, label = "external_telemetry", "Telemetria externa"
        reason = "O destino é um serviço conhecido de telemetria; a ocorrência não reprova uma ação funcional por si só."
        impact = "external_integration"
    elif kind in {"http", "network"} and source_origin and not same_origin:
        classification, label = "external_dependency", "Integração externa"
        reason = "A requisição é de outro domínio. Sem uma asserção funcional ou vínculo causal, seu impacto no recurso testado não está confirmado."
        impact = "unconfirmed"
    elif kind == "http" and same_origin:
        classification, label = "application_http", "Falha HTTP da aplicação"
        reason = "A aplicação respondeu com erro HTTP durante a observação; é uma falha técnica, não um defeito de negócio confirmado automaticamente."
        affects, impact = True, "technical_check_failed"
    elif kind == "network" and same_origin:
        classification, label = "application_network", "Falha de rede da aplicação"
        reason = "Uma requisição da própria aplicação falhou; o resultado funcional precisa ser avaliado pelas asserções do CT."
        affects, impact = True, "technical_check_failed"
    elif kind == "pageerror":
        classification, label = "application_runtime", "Exceção JavaScript"
        reason = "O navegador registrou uma exceção na página. O sinal reprova a verificação técnica, sem confirmar sozinho um defeito de negócio."
        affects, impact = True, "technical_check_failed"
    else:
        classification, label = "unclassified_console", "Registro de console"
        reason = "O console não identifica uma falha funcional ou requisição atribuível com segurança; o registro é preservado para investigação."
        impact = "unconfirmed"
    potential_technical_failure = affects
    association_kind = (issue.get("association") or {}).get("kind")
    if association_kind in {"before_action", "after_action"}:
        affects = False
        impact_message = "Registro fora da execução desta ação; não altera o resultado do CT por coincidência de contexto."
    elif affects:
        impact_message = "Falhou uma verificação técnica da aplicação. Um defeito funcional exige evidência nas asserções do CT."
    elif classification == "external_telemetry":
        impact_message = "Falha na telemetria externa; não reprova a funcionalidade testada por si só."
    elif classification == "request_cancelled":
        impact_message = "Requisição cancelada; sem evidência de falha funcional, não altera o resultado do CT."
    else:
        impact_message = "Impacto funcional não confirmado; a ocorrência é preservada para investigação."
    classified.update(
        classification=classification,
        type=kind or "console",
        label=label,
        impact=impact,
        affects_verdict=affects,
        potential_technical_failure=potential_technical_failure,
        impact_message=impact_message,
        classification_reason=reason,
        occurrence_id=issue.get("occurrence_id") or signal_occurrence_id(issue),
        evidence_channels=list(
            issue.get("evidence_channels")
            or (["network"] if kind in {"http", "network"} else ["console"])
        ),
    )
    return classified


def correlate_issues(issues: list[dict[str, Any]]) -> list[dict[str, Any]]:
    """Pair console/network channels by error, timing and request identity.

    Resource-console URLs can name the page rather than the failed resource.
    Therefore an exact URL match is preferred; otherwise only one unambiguous
    close candidate (250 ms for transport errors) is paired. Distinct requests
    are never deduplicated merely because they have the same status/message.
    """

    records = [copy.deepcopy(issue) for issue in issues]
    network = [
        item
        for item in records
        if (item.get("type") or item.get("kind")) in {"http", "network"}
    ]
    console = [
        item
        for item in records
        if (item.get("type") or item.get("kind")) not in {"http", "network"}
    ]
    matched_console: set[int] = set()
    matched_network: set[int] = set()
    for ci, console_issue in enumerate(console):
        text = str(console_issue.get("message") or "")
        http_match = _RESOURCE_HTTP.search(text)
        network_match = _RESOURCE_NETWORK.search(text)
        if not http_match and not network_match:
            continue
        candidates: list[tuple[float, int]] = []
        for ni, network_issue in enumerate(network):
            if ni in matched_network:
                continue
            if http_match:
                if network_issue.get("status_code") != int(http_match.group(1)):
                    continue
            elif (
                not network_match
                or network_match.group(1).upper()
                not in str(network_issue.get("message") or "").upper()
            ):
                continue
            request_id = console_issue.get("request_id")
            same_request = bool(
                request_id and request_id == network_issue.get("request_id")
            )
            if (
                request_id
                and network_issue.get("request_id")
                and request_id != network_issue["request_id"]
            ):
                continue
            if (
                console_issue.get("screenshot")
                and network_issue.get("screenshot")
                and console_issue["screenshot"] != network_issue["screenshot"]
                and not same_request
            ):
                continue
            ct, nt = (
                timestamp(console_issue.get("occurred_at")),
                timestamp(network_issue.get("occurred_at")),
            )
            delta = abs(ct - nt) if ct is not None and nt is not None else float("inf")
            if (
                delta > (2.0 if http_match else 0.25)
                and delta != float("inf")
                and not same_request
            ):
                continue
            candidates.append((delta, ni))
        if not candidates:
            continue
        exact_requests = [
            item
            for item in candidates
            if console_issue.get("request_id")
            and console_issue.get("request_id") == network[item[1]].get("request_id")
        ]
        if exact_requests:
            candidates = exact_requests
        exact = [
            item
            for item in candidates
            if console_issue.get("url")
            and console_issue.get("url") == network[item[1]].get("url")
        ]
        if exact:
            candidates = exact
        candidates.sort()
        if candidates[0][0] == float("inf") and len(candidates) != 1:
            continue
        # A generic resource error can name the page, not the failed resource.
        # A nearest timestamp alone cannot pick between multiple requests.
        if len(candidates) > 1 and not exact and not exact_requests:
            continue
        if (
            len(candidates) > 1
            and candidates[0][0] == candidates[1][0]
            and not exact_requests
        ):
            continue
        ni = candidates[0][1]
        network[ni].setdefault("related_console_errors", []).append(console_issue)
        network[ni]["evidence_channels"] = ["network", "console"]
        matched_console.add(ci)
        matched_network.add(ni)
    return [
        issue for ci, issue in enumerate(console) if ci not in matched_console
    ] + network


def build_scenario_evidence(
    observation: Observation, decision: AgentDecision, result: ActionResult
) -> dict[str, Any]:
    """Build the same immutable execution payload for local and LLM CTs."""

    evidence = copy.deepcopy(result.evidence)
    evidence.update(
        action=decision.action,
        target=decision.target,
        before_url=result.before_url,
        after_url=result.after_url,
        action_succeeded=result.success,
        assertions=[asdict(assertion) for assertion in result.assertions],
        message=result.message,
        action_started_at=result.started_at,
        action_finished_at=result.finished_at,
    )
    signals = evidence.get("technical_signals")
    if signals is None:
        signals = [
            classify_signal(issue, result.before_url or observation.url)
            for issue in correlate_issues(
                observation.console_errors + observation.network_errors
            )
        ]
    evidence["technical_signals"] = copy.deepcopy(signals)
    if "timeline" not in evidence:
        timeline: list[dict[str, Any]] = []
        before_screenshot = evidence.get("before_screenshot")
        if before_screenshot:
            timeline.append(
                {
                    "kind": "observation",
                    "occurred_at": evidence.get("before_observed_at")
                    or result.started_at,
                    "title": "Antes da ação",
                    "message": "Estado observado antes de executar o controle.",
                    "url": result.before_url,
                    "screenshot": before_screenshot,
                }
            )
        timeline.append(
            {
                "kind": "action",
                "occurred_at": result.started_at,
                "title": action_label(decision.action),
                "message": report_text(decision.rationale),
                "url": result.before_url,
                "action_step": evidence.get("action_step"),
                "step_number": evidence.get("action_step"),
                "target": decision.target,
                "success": result.success,
            }
        )
        for signal in signals:
            timeline.append(
                {
                    "kind": "signal",
                    "occurred_at": signal.get("occurred_at") or result.finished_at,
                    "title": signal.get("label", "Sinal técnico"),
                    "message": signal.get("message", ""),
                    "url": signal.get("url") or result.after_url,
                    "screenshot": signal.get("screenshot"),
                    "signal": copy.deepcopy(signal),
                }
            )
        after_screenshot = result.screenshot or observation.screenshot
        timeline.append(
            {
                "kind": "observation",
                "occurred_at": result.finished_at,
                "title": "Depois da ação",
                "message": report_text(result.message),
                "url": result.after_url,
                **({"screenshot": after_screenshot} if after_screenshot else {}),
            }
        )
        for assertion in result.assertions:
            timeline.append(
                {
                    "kind": "assertion",
                    "occurred_at": result.finished_at,
                    "title": check_label(assertion.kind),
                    "message": report_text(assertion.message),
                    "url": result.after_url,
                    "assertion": asdict(assertion),
                }
            )
        evidence["timeline"] = sorted(
            timeline, key=lambda entry: timestamp(entry.get("occurred_at")) or 0
        )
    preview = evidence.get("action_preview")
    if isinstance(preview, dict):
        action_entries = [
            entry for entry in evidence["timeline"] if entry.get("kind") == "action"
        ]
        step = evidence.get("action_step")
        # A CT can preserve several attempts. The latest result's capture must
        # never be painted onto actions from previous attempts just because
        # they share a scenario. Explicit steps take precedence over timing.
        indexed_matches = [
            entry
            for entry in action_entries
            if step is not None
            and (
                entry.get("step_number")
                if entry.get("step_number") is not None
                else entry.get("action_step")
            ) == step
        ]
        for entry in indexed_matches:
            entry.setdefault("action_preview", copy.deepcopy(preview))
        unindexed_matches = [
            entry
            for entry in action_entries
            if entry.get("step_number") is None
            and entry.get("action_step") is None
            and entry.get("occurred_at") == result.started_at
            and entry.get("target") == decision.target
        ]
        if not indexed_matches and len(unindexed_matches) == 1:
            unindexed_matches[0].setdefault("action_preview", copy.deepcopy(preview))
    for entry in evidence["timeline"]:
        if not entry.get("id"):
            identity = {
                "kind": entry.get("kind"),
                "occurred_at": entry.get("occurred_at"),
                "title": entry.get("title"),
                "screenshot": entry.get("screenshot"),
                "signal_id": (entry.get("signal") or {}).get("occurrence_id"),
            }
            entry["id"] = (
                "entry-"
                + hashlib.sha256(
                    json.dumps(identity, sort_keys=True).encode()
                ).hexdigest()[:24]
            )
    return evidence


def scenario_screenshots(evidence: dict[str, Any], result: ActionResult) -> list[str]:
    screenshots: list[str] = []
    for value in [
        *(item.get("screenshot") for item in evidence.get("timeline", [])),
        *(
            item["action_preview"].get("screenshot")
            for item in evidence.get("timeline", [])
            if item.get("kind") == "action"
            and isinstance(item.get("action_preview"), dict)
        ),
        evidence.get("before_screenshot"),
        result.screenshot,
    ]:
        if value and str(value) not in screenshots:
            screenshots.append(str(value))
    return screenshots
